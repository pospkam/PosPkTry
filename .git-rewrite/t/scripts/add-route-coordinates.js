async function main() {
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL not set');
  }

  const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: process.env.DATABASE_SSL === 'true' ? { rejectUnauthorized: false } : false,
  });
  const client = await pool.connect();

  let updated = 0;

  try {
    await client.query('BEGIN');

    for (const [title, [lat, lng]] of Object.entries(COORDINATES)) {
      const result = await client.query(
        'UPDATE kamchatka_routes SET lat = $1, lng = $2, updated_at = NOW() WHERE title = $3 AND lat IS NULL',
        [lat, lng, title]
      );
      if (result.rowCount > 0) {
        updated += result.rowCount;
        console.log(`✓ ${title}: [${lat}, ${lng}]`);
      }
    }

    await client.query('COMMIT');
    console.log(`\nОбновлено координат: ${updated}`);
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((err) => {
  console.error('Error:', err.message);
  process.exit(1);
});
